function mostrarFiguras() {
  grid.innerHTML = "";

  const correctas = figuras.filter(f => f.silaba === objetivo);
  const incorrectas = figuras.filter(f => f.silaba !== objetivo);

  const figuraCorrecta = correctas[Math.floor(Math.random() * correctas.length)];
  const seleccionIncorrectas = [...incorrectas].sort(() => 0.5 - Math.random()).slice(0, 4);
  const seleccion = [figuraCorrecta, ...seleccionIncorrectas].sort(() => 0.5 - Math.random());

  seleccion.forEach(f => {
    const itemBtn = document.createElement("button");
    itemBtn.type = "button";
    itemBtn.className = "item card-bounce bg-white/90 rounded-3xl p-3 sm:p-4 shadow-xl border-4 border-white/90 flex flex-col items-center justify-center aspect-square focus:outline-none focus:ring-4 focus:ring-sky-300 active:scale-95 transition-all cursor-pointer";
    
    const img = document.createElement("img");
    img.src = f.img;
    img.alt = "figura";
    img.className = "w-full h-full object-contain pointer-events-none drop-shadow-md";

    itemBtn.appendChild(img);
    itemBtn.onclick = () => verificar(f, itemBtn);
    grid.appendChild(itemBtn);
  });
}

